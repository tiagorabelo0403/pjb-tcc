package com.tcc.pjb.backend.service.processual.recursal.workspace;

import com.tcc.pjb.backend.core.processo.recursal.domain.foundation.RecursalInstitutionalOrganizationBlueprint;
import com.tcc.pjb.backend.model.dto.processual.recursal.automation.RecursalAutomationRequest;
import com.tcc.pjb.backend.model.dto.processual.recursal.automation.RecursalAutomationWorkspaceChecklistItemView;
import com.tcc.pjb.backend.model.dto.processual.recursal.automation.RecursalAutomationWorkspaceTrackView;
import java.util.List;

public final class RecursalInstitutionalOrganizationTrackFactory {

    private RecursalInstitutionalOrganizationTrackFactory() {
    }

    public static RecursalAutomationWorkspaceTrackView buildTrack(String recursoPrincipal,
                                                                  RecursalAutomationRequest request) {
        return new RecursalAutomationWorkspaceTrackView(
                "ORGANIZACAO_INSTITUCIONAL_RECURSAL",
                "Organização institucional recursal",
                recursoPrincipal,
                RecursalInstitutionalOrganizationBlueprint.secoes(recursoPrincipal, request),
                RecursalInstitutionalOrganizationBlueprint.checklist(recursoPrincipal, request).entrySet().stream()
                        .map(entry -> new RecursalAutomationWorkspaceChecklistItemView(entry.getKey(), entry.getValue(), true))
                        .toList(),
                List.copyOf(RecursalInstitutionalOrganizationBlueprint.alertas(recursoPrincipal, request))
        );
    }
}
